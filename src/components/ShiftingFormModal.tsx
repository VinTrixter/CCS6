// src/components/ShiftingFormModal.tsx
import { useState, useEffect } from "react";
import { useStore } from "../store/store";
import * as I from "./icons";

interface ModalProps {
    isOpen: boolean;
    onClose: () => void;
    preselectedStudentID?: string;
}

export default function ShiftingFormModal({ isOpen, onClose, preselectedStudentID }: ModalProps) {
    const { students, standings, activeTerm, activeUser, remarks, setRemarks, pushAudit, terms } = useStore();
    const [localSelectedID, setLocalSelectedID] = useState<string>("");

    const [printDate, setPrintDate] = useState<string>("");

    useEffect(() => {
        const timer = setTimeout(() => {
            setPrintDate(new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }));
        }, 0);
        return () => clearTimeout(timer);
    }, []);

    if (!isOpen) return null;

    const currentSelectedID = preselectedStudentID || localSelectedID;

    const atsStandings = standings.filter(ts => ts.termID === activeTerm && ts.termAcademicStatus === 'Advised to Shift');
    const atsStudents = students.filter(s => atsStandings.some(ts => ts.studentID === s.studentID));

    const targetStudent = students.find(s => s.studentID === currentSelectedID);
    const targetStanding = atsStandings.find(ts => ts.studentID === currentSelectedID);
    const termDetails = terms.find(t => t.termID === activeTerm);

    const handlePrint = () => {
        if (!activeUser) return alert("System Error: No active user session detected.");
        if (!targetStudent || !targetStanding) return alert("Please select a valid student record to generate the form.");

        const newRemark = {
            remarkID: `REM-${Date.now()}`,
            content: `Official Shifting Form document automatically generated by ${activeUser.userFirstName} ${activeUser.userLastName}.`,
            timestamp: new Date().toISOString(),
            userID: activeUser.userID,
            standingID: targetStanding.standingID,
            category: "Shifting Recommended"
        };

        setRemarks([...remarks, newRemark]);
        pushAudit("GENERATED_SHIFTING_FORM", targetStudent.studentID);

        window.print();
        onClose();
    };

    return (
        <>
            <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/40 dark:bg-black/60 backdrop-blur-sm print:hidden">
                <div className="w-full max-w-lg overflow-hidden rounded-2xl bg-white dark:bg-slate-800 shadow-2xl transition-colors">
                    <div className="flex items-center justify-between border-b border-slate-100 dark:border-slate-700 bg-slate-50 dark:bg-slate-900/50 px-6 py-4">
                        <h2 className="font-bold text-slate-800 dark:text-slate-100">Generate Shifting Form</h2>
                        <button onClick={onClose} className="text-slate-400 hover:text-slate-600 dark:hover:text-slate-300"><I.X className="h-5 w-5" /></button>
                    </div>

                    <div className="p-6">
                        <label className="mb-2 block text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">Select Flagged Student</label>
                        <select
                            value={currentSelectedID}
                            onChange={(e) => setLocalSelectedID(e.target.value)}
                            disabled={!!preselectedStudentID}
                            className="w-full rounded-lg border border-slate-300 dark:border-slate-600 bg-white dark:bg-slate-900 p-3 text-sm font-semibold text-slate-800 dark:text-slate-200 outline-none focus:border-blue-700 dark:focus:border-blue-500 disabled:bg-slate-100 dark:disabled:bg-slate-800 disabled:opacity-70 transition-colors"
                        >
                            <option value="" disabled>-- Select a student --</option>
                            {atsStudents.map(s => (
                                <option key={s.studentID} value={s.studentID}>{s.studLastName}, {s.studFirstName} ({s.studentID})</option>
                            ))}
                        </select>

                        {!preselectedStudentID && atsStudents.length === 0 && (
                            <p className="mt-2 text-xs font-semibold text-amber-600 dark:text-amber-500">No students are currently flagged as Advised to Shift in this term.</p>
                        )}

                        <div className="mt-6 flex justify-end gap-3 border-t border-slate-100 dark:border-slate-700 pt-4">
                            <button onClick={onClose} className="rounded-lg px-4 py-2 text-sm font-semibold text-slate-500 dark:text-slate-400 hover:bg-slate-100 dark:hover:bg-slate-700 transition">Cancel</button>
                            <button onClick={handlePrint} disabled={!targetStudent} className="flex items-center gap-2 rounded-lg bg-blue-700 dark:bg-blue-600 px-5 py-2 text-sm font-bold text-white shadow-sm hover:bg-blue-800 dark:hover:bg-blue-500 disabled:opacity-50 transition">
                                <I.Printer className="h-4 w-4" /> Print Document
                            </button>
                        </div>
                    </div>
                </div>
            </div>

            {targetStudent && (
                <div className="hidden print:block print:fixed print:inset-0 print:z-[9999] print:bg-white print:text-black">
                    <div className="mx-auto max-w-4xl p-10 font-serif">
                        <div className="mb-10 flex items-center justify-between border-b-2 border-black pb-6">
                            <img src="/imgSilliman.png" alt="Silliman Logo" className="h-24 w-24 object-contain" />
                            <div className="text-center">
                                <h1 className="text-2xl font-black uppercase tracking-widest text-black">Silliman University</h1>
                                <h2 className="text-lg font-bold text-black">College of Computer Studies</h2>
                                <p className="mt-1 text-sm italic text-black">Dumaguete City, Philippines</p>
                            </div>
                            <img src="/imgCCS.jpg" alt="CCS Logo" className="h-24 w-24 rounded-full object-contain" />
                        </div>

                        <div className="mb-12 text-center">
                            <h3 className="text-xl font-bold uppercase underline underline-offset-4 text-black">Official Recommendation for Program Shifting</h3>
                        </div>

                        <div className="space-y-6 text-justify leading-relaxed text-black">
                            <p className="text-right"><strong>Date:</strong> {printDate}</p>
                            <p><strong>To the Office of the Registrar / Admissions:</strong></p>
                            <p>
                                This is to formally notify and certify that <strong className="uppercase">{targetStudent.studFirstName} {targetStudent.studMiddleName || ""} {targetStudent.studLastName}</strong> (Student ID: <strong>{targetStudent.studentID}</strong>), currently enrolled in the <strong className="uppercase">{targetStudent.programCode}</strong> program during the {termDetails?.termSem}, A.Y. {termDetails?.termSY}, has been thoroughly evaluated by the College of Computer Studies Academic Engine.
                            </p>
                            <p>
                                Based on the active academic records and adherence to the retention policies of the college, the student holds a current academic standing of: <strong className="uppercase">Advised to Shift</strong>.
                            </p>
                            <p>
                                The student has failed to meet the minimum quality point requirements or has incurred violations of the major subject failure policy. Therefore, the College of Computer Studies strictly recommends the immediate processing of this student's transfer to another degree program or college within the university.
                            </p>
                            <p className="mt-8">Recommended Destination Program: __________________________________________________</p>
                        </div>

                        <div className="mt-24 grid grid-cols-2 gap-16 text-black">
                            <div className="text-center">
                                {/* FIXED: Safe chaining for activeUser */}
                                <div className="border-b border-black pb-1 uppercase">{activeUser?.userFirstName} {activeUser?.userLastName}</div>
                                <div className="mt-1 text-sm">Prepared By (Dean's Office)</div>
                            </div>
                            <div className="text-center">
                                <div className="border-b border-black pb-1">&nbsp;</div>
                                <div className="mt-1 text-sm">College Dean</div>
                            </div>
                            <div className="col-span-2 mx-auto w-1/2 text-center mt-8">
                                <div className="border-b border-black pb-1">&nbsp;</div>
                                <div className="mt-1 text-sm">Student Signature / Acknowledgment</div>
                            </div>
                        </div>
                    </div>
                </div>
            )}
        </>
    );
}